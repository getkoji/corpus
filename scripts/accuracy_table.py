#!/usr/bin/env python3
"""Generate / verify the README accuracy table from a committed results file.

This is the *cheap* half of accuracy-40 (accuracy_score.py is the expensive
half). It is **stdlib-only** and reads a machine-readable results file produced
by the scorer — it never runs extraction — so CI can verify the README table is
in sync without a model, an API key, or fieldbench.

The table lives between two markers in README.md so it can be replaced and
checked deterministically:

    <!-- ACCURACY-TABLE:START -->
    ...generated table...
    <!-- ACCURACY-TABLE:END -->

Usage:
    python3 scripts/accuracy_table.py render                 # print table
    python3 scripts/accuracy_table.py write                  # update README.md
    python3 scripts/accuracy_table.py check                  # CI: 0 if in sync
"""

import argparse
import json
import pathlib
import sys

START = "<!-- ACCURACY-TABLE:START -->"
END = "<!-- ACCURACY-TABLE:END -->"


def render(results: dict) -> str:
    cats = results["categories"]
    total = results["total"]
    out = [START]
    out.append(
        f"> **Measured, not hand-typed.** Regenerated by "
        f"`scripts/accuracy_table.py` from `.benchmarks/accuracy-latest.json` "
        f"(model `{results['model']}`, scorer `{results['scorer']}`, "
        f"{results['date']}, koji `{results['koji_sha'][:7]}`). CI fails if this "
        f"table drifts from that file. Per-category **N is a capped sample** — "
        f"numbers are scoped to the documents actually scored, shown in the N column."
    )
    out.append("")
    out.append("| Category | N scored | Accuracy | Real | Synthetic |")
    out.append("|---|---:|---:|---:|---:|")
    for cat in sorted(cats, key=lambda c: -(cats[c]["accuracy"] or 0)):
        c = cats[cat]

        def cell(v):
            return f"{v:.1f}%" if v is not None else "—"

        out.append(
            f"| **{cat}** | {c['documents']} | **{cell(c['accuracy'])}** | "
            f"{cell(c['real_accuracy'])} | {cell(c['synthetic_accuracy'])} |"
        )
    out.append(
        f"| **TOTAL** | **{total['documents']}** | **{cell_total(total['accuracy'])}** | | |"
    )
    out.append("")
    out.append(END)
    return "\n".join(out)


def cell_total(v):
    return f"{v:.1f}%" if v is not None else "—"


def splice(readme: str, block: str) -> str:
    if START not in readme or END not in readme:
        raise SystemExit(
            f"markers not found in README.md — insert {START} ... {END} where the "
            "accuracy table should live"
        )
    pre = readme.split(START)[0]
    post = readme.split(END, 1)[1]
    return pre + block + post


def extract_block(readme: str) -> str:
    if START not in readme or END not in readme:
        return ""
    return START + readme.split(START, 1)[1].split(END, 1)[0] + END


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("mode", choices=["render", "write", "check"])
    ap.add_argument(
        "--results",
        type=pathlib.Path,
        default=pathlib.Path(".benchmarks/accuracy-latest.json"),
    )
    ap.add_argument("--readme", type=pathlib.Path, default=pathlib.Path("README.md"))
    args = ap.parse_args()

    if not args.results.exists():
        sys.exit(
            f"results file not found: {args.results} — run accuracy_score.py first"
        )
    results = json.loads(args.results.read_text())
    block = render(results)

    if args.mode == "render":
        print(block)
        return 0

    readme = args.readme.read_text()
    if args.mode == "write":
        args.readme.write_text(splice(readme, block))
        print(f"updated {args.readme}")
        return 0

    # check
    current = extract_block(readme)
    if current.strip() != block.strip():
        print(
            f"error: {args.readme} accuracy table is out of sync with "
            f"{args.results}. Run: python3 scripts/accuracy_table.py write",
            file=sys.stderr,
        )
        return 1
    print(f"{args.readme} accuracy table is in sync with {args.results}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
